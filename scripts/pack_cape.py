#!/usr/bin/env python3
"""Make a single Cosmetics cape ZIP. The DLL builds its Persona binary at launch.

For animated Persona, provide the *complete* prebuilt native bundle instead of a
sprite sheet. Static PNGs do not imply animated Persona textures.
"""
import argparse
import json
from pathlib import Path
import sys
import uuid
from zipfile import ZipFile, ZIP_DEFLATED

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cape_pack_utils import (check_png, valid_name, validated_rarity,
                             validated_start_date, validate_native, safe_filename)


def create(source, output, name=None, author="Player", item_id=None, persona_zip=None,
           rarity="common", start_date=None):
    source = Path(source) if source is not None else None
    data = source.read_bytes() if source is not None and source.is_file() else None
    if data is not None:
        check_png(data)
    if data is None and not persona_zip:
        raise ValueError("provide a PNG or --persona-zip")
    title = valid_name(name or (source.stem if data is not None else Path(persona_zip).stem), "cape name")
    author = valid_name(author, "cape author")
    rarity = validated_rarity(rarity)
    validated_start_date(start_date)
    manifest = {"name": title, "author": author, "rarity": rarity}
    if item_id:
        manifest["id"] = str(uuid.UUID(item_id))
    if start_date:
        manifest["startDate"] = start_date
    binary = validate_native(persona_zip) if persona_zip else None
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(output, "w", ZIP_DEFLATED) as archive:
        archive.writestr("cape.json", json.dumps(manifest, ensure_ascii=False, indent=2))
        if data is not None:
            archive.writestr("cape.png", data)
        if binary is not None:
            archive.writestr("persona.zip", binary)
    if output.stat().st_size > 64 * 1024 * 1024:
        output.unlink(missing_ok=True)
        raise ValueError("outer cape ZIP exceeds 64 MiB")
    print(f"Created {output}: {title!r} native_persona={'yes' if binary else 'no'}")
    print("PNG -> Persona meta/index generated by Cosmetics DLL at startup. "
          "Native animated Persona resources are preserved unchanged.")
    return output


def main():
    parser = argparse.ArgumentParser(description="Create a validated Cosmetics local cape ZIP")
    parser.add_argument("png", nargs="?", help="Original cape PNG (UV/HD processing occurs in Cosmetics DLL)")
    parser.add_argument("--name", help="Displayed name")
    parser.add_argument("--author", default="Player")
    parser.add_argument("--id", help="Fixed item UUID across renames")
    parser.add_argument("--rarity", choices=["common","uncommon","rare","epic","legendary"], default="common")
    parser.add_argument("--start-date", help="Optional real YYYY-MM-DDTHH:MM:SSZ")
    parser.add_argument("--persona-zip", help="Complete Persona ZIP or ppack0.zip bundle (preserves animation)")
    parser.add_argument("--out", help="Output ZIP (default capes/<name>.zip)")
    args = parser.parse_args()
    if not args.png and not args.persona_zip:
        parser.error("provide png or --persona-zip")
    title = args.name or Path(args.png or args.persona_zip).stem
    try:
        out = args.out or f"capes/{safe_filename(title)}.zip"
        create(args.png, out, args.name, args.author, args.id, args.persona_zip,
               args.rarity, args.start_date)
    except (ValueError, OSError, KeyError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    main()
